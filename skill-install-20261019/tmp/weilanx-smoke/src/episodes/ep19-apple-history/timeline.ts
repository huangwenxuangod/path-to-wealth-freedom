const lerp = (pts: [number, number][], v: number, a: 0 | 1) => {
  const b = a ? 0 : 1;
  for (let i = 1; i < pts.length; i++) if (v <= pts[i][a]) return pts[i - 1][b] + ((v - pts[i - 1][a]) / (pts[i][a] - pts[i - 1][a])) * (pts[i][b] - pts[i - 1][b]);
  return pts[pts.length - 1][b];
};

/** 年份 → 桌面横坐标 */
export const yx = (year: number) => lerp(ANCHORS, year, 0);
/** 桌面横坐标 → 年份 */
export const xy = (x: number) => lerp(ANCHORS, x, 1);

